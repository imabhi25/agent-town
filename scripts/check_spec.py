"""Model-check spec/AgentTown.tla with TLC: the correct design must pass, and every deliberately
broken variant must fail with the expected counterexample.

    python scripts/check_spec.py                 # all variants, rewrite results + README block
    python scripts/check_spec.py --only correct  # one variant (does not touch the README)
    python scripts/check_spec.py --report        # rewrite the README block from the results file
    python scripts/check_spec.py --check         # exit 1 if the README block is out of date
    python scripts/check_spec.py --ci            # all variants, fail on a surprise, README untouched

Needs Java 11+. tla2tools.jar is downloaded once (pinned version, checked against its SHA-256)
into .cache/, or set TLA2TOOLS=/path/to/tla2tools.jar.

Writes results/spec/tlc.jsonl (one line per variant) and, for each variant that fails,
results/spec/<variant>.trace.txt with TLC's counterexample. The README block between the
SPEC:START and SPEC:END markers is generated from tlc.jsonl; tests/test_spec_report.py checks it.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
RESULTS = ROOT / "results" / "spec"
README = ROOT / "README.md"
START, END = "<!-- SPEC:START (generated by scripts/check_spec.py) -->", "<!-- SPEC:END -->"

TLA_VERSION = "1.8.0"
TLA_URL = f"https://github.com/tlaplus/tlaplus/releases/download/v{TLA_VERSION}/tla2tools.jar"
TLA_SHA256 = "67f9575c3b9ef7a0787b1bded34812862ffe79d711298e5a75b1a77720b19928"

# variant -> (what it changes, what TLC must report). "ok" = no error; otherwise the name of the
# violated invariant, or "liveness" for a violated temporal property.
VARIANTS = {
    "correct_faults": ("The design as built; up to 2 crashes or heartbeat lapses", "ok"),
    "correct_errors": ("The design as built; up to 2 provider errors (retries)", "ok"),
    "correct_mixed": ("The design as built; 1 crash or lapse and 1 provider error", "ok"),
    "ack_before_commit": ("XACK when the job is claimed, before the commit", "NoLostJob"),
    "no_goal_lock": ("Finish a task without locking the goal row", "NoStuckTask"),
    "plain_zrem": ("Retry mover removes the delayed entry with a plain ZREM", "NoLostJob"),
    "name_only_heartbeat": (
        '"Busy" = a worker with that name is alive (no lock token)',
        "liveness",
    ),
}
# The two variants that were the real code before the model found the bugs.
FOUND_BUGS = {"plain_zrem", "name_only_heartbeat"}


def tla_jar() -> Path:
    env = os.environ.get("TLA2TOOLS")
    if env:
        return Path(env)
    jar = ROOT / ".cache" / f"tla2tools-{TLA_VERSION}.jar"
    if not jar.exists():
        jar.parent.mkdir(exist_ok=True)
        print(f"downloading tla2tools {TLA_VERSION} ...", file=sys.stderr)
        data = urllib.request.urlopen(TLA_URL, timeout=60).read()
        if hashlib.sha256(data).hexdigest() != TLA_SHA256:
            raise SystemExit("tla2tools.jar checksum mismatch; refusing to run it")
        jar.write_bytes(data)
    return jar


def _int(pattern: str, text: str) -> int | None:
    m = re.findall(pattern, text)
    return int(m[-1].replace(",", "")) if m else None


def parse(output: str) -> dict:
    """Pull the outcome and the numbers out of TLC's output."""
    if "Model checking completed. No error has been found." in output:
        outcome = "ok"
    elif m := re.search(r"Error: Invariant (\w+) is violated", output):
        outcome = m.group(1)
    elif re.search(
        r"Temporal propert(y|ies) .*were violated|Temporal properties were violated", output
    ):
        outcome = "liveness"
    else:
        outcome = "tlc-error"
    m = re.search(r"([\d,]+) states generated, ([\d,]+) distinct states found", output)
    return {
        "outcome": outcome,
        "states": int(m.group(1).replace(",", "")) if m else None,
        "distinct": int(m.group(2).replace(",", "")) if m else None,
        "depth": _int(r"depth of the complete state graph search is (\d+)", output),
        "trace_length": len(re.findall(r"^State \d+:", output, re.MULTILINE)) or None,
    }


def constants(cfg: Path) -> dict:
    found = dict(
        re.findall(r"^\s+(MaxFaults|MaxProviderErrors) = (\d+)", cfg.read_text(), re.MULTILINE)
    )
    return {k: int(v) for k, v in found.items()}


def run(variant: str, jar: Path) -> dict:
    cfg = SPEC / f"{variant}.cfg"
    with tempfile.TemporaryDirectory() as meta:
        cmd = ["java", "-XX:+UseParallelGC", "-cp", str(jar), "tlc2.TLC", "-workers", "auto",
               "-noGenerateSpecTE", "-metadir", meta, "-config", cfg.name, "MC.tla"]  # fmt: skip
        t0 = time.monotonic()
        proc = subprocess.run(cmd, cwd=SPEC, capture_output=True, text=True, check=False)
        seconds = round(time.monotonic() - t0, 1)
    output = proc.stdout + proc.stderr
    result = {"variant": variant, **parse(output), "seconds": seconds, **constants(cfg)}
    result["expected"] = VARIANTS[variant][1]
    result["as_expected"] = result["outcome"] == result["expected"]
    trace = RESULTS / f"{variant}.trace.txt"
    if result["outcome"] not in ("ok", "tlc-error"):
        start = output.find("Error:")
        trace.write_text(output[start:].split("\nFinished checking")[0].rstrip() + "\n")
    else:
        trace.unlink(missing_ok=True)
        if result["outcome"] == "tlc-error":
            print(output[-3000:], file=sys.stderr)
    return result


def _n(x: int | None) -> str:
    return "-" if x is None else f"{x:,}"


def report(rows: list[dict]) -> str:
    by = {r["variant"]: r for r in rows}
    correct = [by[n] for n in VARIANTS if VARIANTS[n][1] == "ok"]
    states = sum(r["distinct"] or 0 for r in correct)
    lines = [
        (
            f"**TLC explored {_n(states)} distinct states of the design as built (every "
            "interleaving of 2 workers and a 3-task diamond, with crashes, heartbeat lapses and "
            "provider errors) and found no violation of any safety or liveness property.** Each "
            "deliberately broken variant fails with a counterexample."
        ),
        "",
        "| Variant | What changes | Crashes / errors | TLC result |",
        "|---|---|---|---|",
    ]
    for name, (what, _) in VARIANTS.items():
        r = by[name]
        if r["outcome"] == "ok":
            result = f"no violation ({_n(r['distinct'])} states)"
        else:
            prop = (
                "liveness (`GoalFinishes`)" if r["outcome"] == "liveness" else f"`{r['outcome']}`"
            )
            result = (f"violates {prop}, {r['trace_length']}-step trace "
                      f"([trace](results/spec/{name}.trace.txt))")  # fmt: skip
        if not r["as_expected"]:
            result += f" **(expected {r['expected']})**"
        found = " **(the code before the model found it; fixed)**" if name in FOUND_BUGS else ""
        budget = f"{r['MaxFaults']} / {r['MaxProviderErrors']}"
        lines.append(f"| `{name}` | {what}{found} | {budget} | {result} |")
    return "\n".join(lines)


def load() -> list[dict]:
    path = RESULTS / "tlc.jsonl"
    return [json.loads(x) for x in path.read_text().splitlines() if x.strip()]


def readme_with(block: str) -> str:
    text = README.read_text()
    a, b = text.index(START) + len(START), text.index(END)
    return text[:a] + "\n" + block + "\n" + text[b:]


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--only", choices=VARIANTS)
    p.add_argument("--report", action="store_true")
    p.add_argument("--check", action="store_true")
    p.add_argument("--ci", action="store_true", help="run every variant, do not touch the README")
    a = p.parse_args()

    if a.check:
        if README.read_text() != readme_with(report(load())):
            raise SystemExit("README spec block is out of date: run scripts/check_spec.py --report")
        return
    if not a.report:
        RESULTS.mkdir(parents=True, exist_ok=True)
        jar = tla_jar()
        rows = []
        for name in [a.only] if a.only else VARIANTS:
            print(f"checking {name} ...", file=sys.stderr, flush=True)
            r = run(name, jar)
            print(json.dumps(r), flush=True)
            rows.append(r)
        if any(not r["as_expected"] for r in rows):
            raise SystemExit("a variant did not give the expected TLC result")
        if a.only or a.ci:
            return
        (RESULTS / "tlc.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
    README.write_text(readme_with(report(load())))


if __name__ == "__main__":
    main()
