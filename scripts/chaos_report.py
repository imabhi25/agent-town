"""Turn the chaos campaign's results file into the README numbers. No number is typed by hand.

    python scripts/chaos_report.py            # rewrite the README block from results
    python scripts/chaos_report.py --check    # exit 1 if the README block is out of date (CI)

The README block sits between the CHAOS:START and CHAOS:END comment markers.
tests/test_chaos_report.py checks it matches the committed results file, so the README cannot
drift from the data.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results" / "chaos" / "campaign.jsonl"
README = ROOT / "README.md"
START, END = "<!-- CHAOS:START (generated by scripts/chaos_report.py) -->", "<!-- CHAOS:END -->"
HEAD_START = "<!-- CHAOS-HEADLINE:START (generated by scripts/chaos_report.py) -->"
HEAD_END = "<!-- CHAOS-HEADLINE:END -->"


def load(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text().splitlines() if x.strip()]


def _n(x: int) -> str:
    return f"{x:,}"


def summarize(rows: list[dict]) -> dict:
    def total(mode: str, key: str) -> int:
        return sum(r[key] for r in rows if r["mode"] == mode)

    def fault(mode: str, key: str) -> int:
        return sum(r["faults"][key] for r in rows if r["mode"] == mode)

    def kind(mode: str, k: str) -> int:
        return sum(r["violations"].get(k, 0) for r in rows if r["mode"] == mode)

    s = {}
    for mode in ("safe", "unsafe"):
        runs = [r for r in rows if r["mode"] == mode]
        s[mode] = {
            "runs": len(runs),
            "runs_with_violations": sum(r["total_violations"] > 0 for r in runs),
            "jobs": total(mode, "jobs"),
            "succeeded": total(mode, "succeeded"),
            "dead": total(mode, "dead"),
            "violations": total(mode, "total_violations"),
            "lost": kind(mode, "lost"),
            "duplicate_outputs": kind(mode, "duplicate_output"),
            "duplicate_effects": kind(mode, "duplicate_effect"),
            "worker_kills": fault(mode, "worker_kills"),
            "worker_kills_mid_job": fault(mode, "worker_kills_mid_job"),
            "dispatcher_kills": fault(mode, "dispatcher_kills"),
            "redis_restarts": fault(mode, "redis_restarts"),
            "redelivered_jobs": total(mode, "redelivered_jobs"),
            "workers": sorted({r["workers"] for r in runs}),
        }
    s["campaign"] = rows[0]["campaign"] if rows else ""
    return s


def render(rows: list[dict]) -> str:
    s = summarize(rows)
    safe, bad = s["safe"], s["unsafe"]
    faults = safe["worker_kills"] + safe["dispatcher_kills"] + safe["redis_restarts"]
    workers = "/".join(str(w) for w in safe["workers"])
    def row(label: str, ok: str, broken: str) -> str:
        return f"| {label} | {ok} | {broken} |"

    def both(label: str, key: str) -> str:
        return row(label, _n(safe[key]), _n(bad[key]))

    def kills(m: dict) -> str:
        return f"{_n(m['worker_kills'])} ({_n(m['worker_kills_mid_job'])} mid-job)"

    headline = (
        f"**{_n(safe['jobs'])} jobs, {_n(faults)} injected crashes, {safe['lost']} lost jobs, "
        f"{safe['duplicate_outputs']} duplicate outputs** "
        f"({safe['runs']} runs, campaign `{s['campaign']}`)."
    )
    dups = "{duplicate_outputs} / {duplicate_effects}"
    footer = (
        f"{workers} worker processes per run, mock LLM, local Postgres and Redis. "
        "Raw data: [`results/chaos/campaign.jsonl`](results/chaos/campaign.jsonl)."
    )
    lines = [
        START,
        headline,
        "",
        row("", "Correct worker", "Deliberately broken worker (XACK before commit)"),
        "|---|---|---|",
        both("Runs", "runs"),
        both("Jobs submitted", "jobs"),
        row("Worker processes killed with SIGKILL", kills(safe), kills(bad)),
        both("Dispatcher killed with SIGKILL", "dispatcher_kills"),
        both("Redis killed with SIGKILL and restarted", "redis_restarts"),
        both("Jobs that ran more than once", "redelivered_jobs"),
        row("Lost jobs", f"**{safe['lost']}**", _n(bad["lost"])),
        row(
            "Duplicate outputs / duplicate success events",
            f"**{dups.format(**safe)}**",
            dups.format(**bad),
        ),
        row(
            "Runs where the checker found a violation",
            f"{safe['runs_with_violations']} of {safe['runs']}",
            f"**{bad['runs_with_violations']} of {bad['runs']}**",
        ),
        "",
        footer,
        END,
    ]
    return "\n".join(lines)


def render_headline(rows: list[dict]) -> str:
    s = summarize(rows)
    safe, bad = s["safe"], s["unsafe"]
    faults = safe["worker_kills"] + safe["dispatcher_kills"] + safe["redis_restarts"]
    sentence = (
        f"**Delivery checked under real crashes:** {_n(safe['jobs'])} jobs, {_n(faults)} "
        f"processes killed with SIGKILL (workers, dispatcher, Redis), {safe['lost']} lost jobs, "
        f"{safe['duplicate_outputs']} duplicate outputs. A deliberately broken worker was "
        f"caught in {bad['runs_with_violations']} of {bad['runs']} runs. "
        "[How it is checked](#checked-under-crashes)."
    )
    return f"{HEAD_START}\n{sentence}\n{HEAD_END}"


def replace_block(text: str, block: str, start: str = START, end: str = END) -> str:
    i, j = text.index(start), text.index(end) + len(end)
    return text[:i] + block + text[j:]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true")
    p.add_argument("--results", default=str(RESULTS))
    a = p.parse_args(argv)
    rows = load(Path(a.results))
    block = render(rows)
    text = README.read_text()
    updated = replace_block(text, block)
    updated = replace_block(updated, render_headline(rows), HEAD_START, HEAD_END)
    if a.check:
        if updated != text:
            print("README chaos block is out of date: run python scripts/chaos_report.py")
            return 1
        return 0
    README.write_text(updated)
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
