"""Turn results/bench/engine.jsonl into the README benchmark blocks. No number is typed by hand.

    python scripts/bench_report.py            # rewrite the README blocks from results
    python scripts/bench_report.py --check    # exit 1 if they are out of date

tests/test_bench_report.py runs the check, so the README cannot drift from the data.
"""

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from chaos_report import README, load, replace_block

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results" / "bench" / "engine.jsonl"
START, END = "<!-- BENCH:START (generated by scripts/bench_report.py) -->", "<!-- BENCH:END -->"
HEAD_START = "<!-- BENCH-HEADLINE:START (generated by scripts/bench_report.py) -->"
HEAD_END = "<!-- BENCH-HEADLINE:END -->"


def _by(rows: list[dict], kind: str) -> list[dict]:
    return [r for r in rows if r["kind"] == kind]


def summarize(rows: list[dict]) -> dict:
    meta = _by(rows, "meta")[0]
    tp = {r["workers"]: r for r in _by(rows, "throughput")}
    lat = {r["workers"]: r for r in _by(rows, "latency")}
    rec = _by(rows, "recovery")
    best = max(tp.values(), key=lambda r: r["jobs_per_s"])
    reclaim = [r["kill_to_reclaim_s"] for r in rec]
    done = [r["kill_to_done_s"] for r in rec]
    return {
        "meta": meta,
        "throughput": tp,
        "latency": lat,
        "best": best,
        "recovery": {
            "trials": len(rec),
            "lease_s": rec[0]["lease_s"] if rec else None,
            "heartbeat_ttl_s": rec[0]["heartbeat_ttl_s"] if rec else None,
            "recovery_interval_s": rec[0]["recovery_interval_s"] if rec else None,
            "reclaim_median_s": statistics.median(reclaim) if rec else None,
            "reclaim_max_s": max(reclaim) if rec else None,
            "done_median_s": statistics.median(done) if rec else None,
            "done_max_s": max(done) if rec else None,
        },
    }


def render(rows: list[dict]) -> str:
    s = summarize(rows)
    meta, rec = s["meta"], s["recovery"]
    lo, hi = (int(x * 1000) for x in meta["mock_latency_s"])
    lines = [
        START,
        (
            "| Worker processes | Ideal jobs/s | Measured jobs/s | Of ideal | "
            "Latency p50 / p95 / p99 at 60% load |"
        ),
        "|---|---|---|---|---|",
    ]
    for n, t in sorted(s["throughput"].items()):
        lt = s["latency"].get(n)
        latency = f"{lt['p50_ms']} / {lt['p95_ms']} / {lt['p99_ms']} ms" if lt else "n/a"
        share = round(100 * t["jobs_per_s"] / t["ideal_jobs_per_s"])
        lines.append(
            f"| {n} | {t['ideal_jobs_per_s']:g} | {t['jobs_per_s']:g} | {share}% | {latency} |"
        )
    lines += [
        "",
        (
            f"**Recovery after kill -9** (production clocks: lease {rec['lease_s']:g} s, heartbeat TTL "
            f"{rec['heartbeat_ttl_s']:g} s, recovery check every {rec['recovery_interval_s']:g} s; "
            f"{rec['trials']} trials): another worker took the job over after "
            f"{rec['reclaim_median_s']:.1f} s median ({rec['reclaim_max_s']:.1f} s max), and it "
            f"finished {rec['done_median_s']:.1f} s median ({rec['done_max_s']:.1f} s max) after "
            "the kill. Recovery time is set by the lease, by design: it is the price of not "
            "stealing jobs from workers that are only slow."
        ),
        "",
        (
            f"{meta['cores']} cores ({meta['cpu']}), Postgres {meta['postgres'].split()[0]}, "
            f"Python {meta['python']}, local Redis; mock LLM {lo} to {hi} ms per call, so one worker's "
            f"ideal is {1000 / ((lo + hi) / 2):g} jobs/s. One run per row (run `{meta['run']}`). "
            "Latency is job created to job completed: outbox poll, queue wait, the mock call, "
            "the commit. A value above 100% of ideal is noise in the random mock latency. Raw data: [`results/bench/engine.jsonl`](results/bench/engine.jsonl)."
        ),
        END,
    ]
    return "\n".join(lines)


def render_headline(rows: list[dict]) -> str:
    s = summarize(rows)
    best, rec = s["best"], s["recovery"]
    lt = s["latency"].get(best["workers"])
    p99 = f", p99 {lt['p99_ms']} ms at 60% load" if lt else ""
    sentence = (
        f"**Measured:** {best['jobs_per_s']:g} jobs/s with {best['workers']} worker processes "
        f"on {s['meta']['cores']} cores (mock LLM){p99}; a job whose worker is killed with SIGKILL is "
        f"taken over in {rec['reclaim_median_s']:.1f} s (median, {rec['lease_s']:g} s lease). "
        "[Benchmarks](#benchmarks)."
    )
    return f"{HEAD_START}\n{sentence}\n{HEAD_END}"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true")
    p.add_argument("--results", default=str(RESULTS))
    a = p.parse_args(argv)
    rows = load(Path(a.results))
    text = README.read_text()
    updated = replace_block(text, render_headline(rows), HEAD_START, HEAD_END)
    updated = replace_block(updated, render(rows), START, END)
    if a.check:
        if updated != text:
            print("README benchmark blocks are out of date: run python scripts/bench_report.py")
            return 1
        return 0
    README.write_text(updated)
    print(render_headline(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
